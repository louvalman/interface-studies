/*
  Writes the demo pages' chrome into every demo.html: the language switch,
  the theme switch and the head script that sets the theme before the first
  paint, the crossfade, and the Sound switch on a page whose study makes a
  noise. The source is the other files in this folder; each page gets its
  own copy, written between marker comments.

    node tools/demo-chrome/build.js                    # every page
    node tools/demo-chrome/build.js 2026-10-mode-dial  # just these folders
    node tools/demo-chrome/build.js --check            # write nothing; 1 if
                                                       # a page is stale, 2
                                                       # on an error

  Run it after changing anything here, or after adding a page. The output is
  committed. Nothing loads from this folder at runtime: delete tools/ and
  every page keeps its switches, because every page holds its own copy. See
  "The demo page's chrome is written once and generated into every page" in
  CLAUDE.md.

  A page carries six regions — head, css, crossfade, controls, any number of
  sound-mirror, and script — each opened by a marker naming the region and
  closed by its twin. Everything between the two is this generator's and is
  replaced wholesale; nothing outside them is touched. The page's own part
  of the chrome, its Danish and its hooks, is a <script data-demo-page>
  setting window.demoPage, just before the script region, and the generator
  reads it only to check it.

  It throws, naming the file and the line, rather than write a page it cannot
  account for, and it writes nothing at all if any page fails. Plain Node,
  no dependencies.
*/
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

// The crossfade's length, in the stylesheet and in the script that takes the
// class off again. One number, written into both.
const CROSSFADE_MS = 420;

const HERE = __dirname;
const ROOT = path.join(HERE, '..', '..');
const NOTE = 'generated by tools/demo-chrome/build.js — edit there, not here';

const REGIONS = ['head', 'css', 'crossfade', 'controls', 'sound-mirror', 'script'];
const CSS_REGIONS = new Set(['css', 'crossfade']);
const FLAGS = { controls: ['sound'] };

// The six tokens the chrome reads, which every page has to declare.
const TOKENS = ['gutter', 'fg', 'dim', 'accent', 'chip', 'line'];

// Chrome that may only appear inside a region.
const OUTSIDE = [
  'data-theme-toggle',
  'data-lang=',
  'data-sound-toggle',
  'id="demo-theme-bite"',
  'class="demo__lang',
  'class="demo__theme',
  'class="demo__sound',
  "interface-studies:lang'",
  "interface-studies:theme'",
  "classList.add('is-theming')"
];
const CHROME_SELECTOR = /^\s*\.demo__(?:lang|theme|sound)/;
const CONTROLS_SELECTOR = /^\s*\.demo__controls\b/;

const OPEN = /^([ \t]*)(<!--|\/\*) demo-chrome:([a-z-]+)((?:[ \t]+\+[a-z-]+)*)(?:[ \t]+·[^\n]*?)?[ \t]*(-->|\*\/)[ \t]*$/;
const CLOSE = /^([ \t]*)(<!--|\/\*) \/demo-chrome:([a-z-]+) (-->|\*\/)[ \t]*$/;

class ChromeError extends Error {}

function fail(file, line, message) {
  throw new ChromeError(file + (line ? ':' + line : '') + ': ' + message);
}

/* ---- sources ------------------------------------------------------------ */

// Every placeholder each source must still hold. A source reshaped so that
// one has gone throws here, rather than emitting a page with a hole in it.
const PLACEHOLDERS = {
  'head.html': [],
  'controls.html': ['{{SOUND}}'],
  'sound-button.html': ['{{LOCAL}}'],
  'chrome.css': [],
  'sound.css': [],
  'crossfade.css': ['{{CROSSFADE_MS}}'],
  'chrome.js': ['{{CROSSFADE_MS}}', '/*{{SOUND}}*/'],
  'sound.js': []
};

function loadSources() {
  const src = {};
  Object.keys(PLACEHOLDERS).forEach(function (name) {
    const file = path.join('tools', 'demo-chrome', name);
    let text;
    try { text = fs.readFileSync(path.join(HERE, name), 'utf8'); } catch (err) { fail(file, 0, 'missing'); }
    if (text.indexOf('\r') >= 0) fail(file, 0, 'carries a carriage return; sources are LF-only');
    if (text.indexOf('demo-chrome:') >= 0) fail(file, 0, 'may not contain "demo-chrome:", which only a marker may');
    const wanted = PLACEHOLDERS[name];
    wanted.forEach(function (token) {
      if (text.indexOf(token) < 0) fail(file, 0, 'no longer holds the placeholder ' + token);
    });
    const left = text.replace(/\/\*\{\{SOUND\}\}\*\/|\{\{(?:SOUND|LOCAL|CROSSFADE_MS)\}\}/g, function (m) {
      return wanted.indexOf(m) >= 0 ? '' : m;
    });
    if (left.indexOf('{{') >= 0) fail(file, 0, 'holds a placeholder the generator does not fill');
    src[name] = text.replace(/\n$/, '');
  });
  return src;
}

/* ---- rendering ---------------------------------------------------------- */

function indent(text, pad) {
  return text.split('\n').map(function (line) { return line.length ? pad + line : line; }).join('\n');
}

// A placeholder on a line of its own becomes a block at that line's own
// indentation. An empty block takes the line with it, and the blank line
// after it, so a page without the sound has no gap where it would be.
function block(text, token, body) {
  const lines = text.split('\n');
  const at = lines.map(function (l) { return l.trim(); }).indexOf(token);
  if (at < 0 || lines.map(function (l) { return l.trim(); }).lastIndexOf(token) !== at) {
    throw new ChromeError('tools/demo-chrome: ' + token + ' must sit on a line of its own, once');
  }
  const pad = lines[at].match(/^[ \t]*/)[0];
  if (body === '') {
    lines.splice(at, lines[at + 1] !== undefined && lines[at + 1].trim() === '' ? 2 : 1);
  } else {
    Array.prototype.splice.apply(lines, [at, 1].concat(indent(body, pad).split('\n')));
  }
  return lines.join('\n');
}

function inline(text, token, value) {
  return text.split(token).join(value);
}

function render(src, name, sound) {
  const ms = String(CROSSFADE_MS);
  const button = function (local) { return inline(src['sound-button.html'], '{{LOCAL}}', local); };
  switch (name) {
    case 'head':
      return src['head.html'];
    case 'css':
      return src['chrome.css'] + (sound ? '\n\n' + src['sound.css'] : '');
    case 'crossfade':
      return inline(src['crossfade.css'], '{{CROSSFADE_MS}}', ms);
    case 'controls':
      return block(src['controls.html'], '{{SOUND}}', sound ? button('') : '');
    case 'sound-mirror':
      return button(' demo__sound--local');
    case 'script':
      return '<script>\n'
        + block(inline(src['chrome.js'], '{{CROSSFADE_MS}}', ms), '/*{{SOUND}}*/', sound ? src['sound.js'] : '')
        + '\n</script>';
  }
  throw new ChromeError('no source for region ' + name);
}

function opening(region) {
  const flags = region.flags.map(function (f) { return ' +' + f; }).join('');
  return CSS_REGIONS.has(region.name)
    ? region.pad + '/* demo-chrome:' + region.name + flags + ' · ' + NOTE + ' */'
    : region.pad + '<!-- demo-chrome:' + region.name + flags + ' · ' + NOTE + ' -->';
}

/* ---- parsing ------------------------------------------------------------ */

// The regions of a page, by line (0-based), with the structure checked:
// every opening closed by its own twin, no nesting, known names in the
// right comment syntax, flags only where they mean something.
function parse(text, file) {
  const lines = text.split('\n');
  const regions = [];
  let open = null;
  lines.forEach(function (line, i) {
    if (line.indexOf('demo-chrome:') < 0) return;
    const n = i + 1;
    let m = line.match(OPEN);
    if (m) {
      const name = m[3];
      if (open) fail(file, n, 'demo-chrome:' + name + ' opens inside ' + open.name + ', opened at line ' + (open.open + 1));
      if (REGIONS.indexOf(name) < 0) fail(file, n, 'unknown region "' + name + '"');
      checkSyntax(file, n, name, m[2], m[5]);
      const flags = m[4].split(/[ \t]+\+/).filter(Boolean).map(function (f) { return f.trim(); });
      flags.forEach(function (f) {
        if (!FLAGS[name] || FLAGS[name].indexOf(f) < 0) fail(file, n, 'flag +' + f + ' is not allowed on ' + name);
      });
      if (new Set(flags).size !== flags.length) fail(file, n, 'a flag is repeated');
      open = { name: name, flags: flags, pad: m[1], open: i, close: -1 };
      return;
    }
    m = line.match(CLOSE);
    if (m) {
      const name = m[3];
      if (!open) fail(file, n, '/demo-chrome:' + name + ' closes a region that was never opened');
      if (open.name !== name) fail(file, n, '/demo-chrome:' + name + ' closes ' + open.name + ', opened at line ' + (open.open + 1));
      checkSyntax(file, n, name, m[2], m[4]);
      open.close = i;
      regions.push(open);
      open = null;
      return;
    }
    fail(file, n, '"demo-chrome:" outside a well-formed marker');
  });
  if (open) fail(file, open.open + 1, 'demo-chrome:' + open.name + ' is never closed');
  return { lines: lines, regions: regions };
}

function checkSyntax(file, n, name, opener, closer) {
  const css = CSS_REGIONS.has(name);
  if ((opener === '/*') !== (closer === '*/')) fail(file, n, 'marker opens with ' + opener + ' and closes with ' + closer);
  if (css && opener !== '/*') fail(file, n, name + ' sits in a stylesheet and takes a /* */ marker');
  if (!css && opener !== '<!--') fail(file, n, name + ' sits in markup and takes a <!-- --> marker');
}

/* ---- the checks --------------------------------------------------------- */

function firstLine(lines, re, from, to) {
  for (let i = from || 0; i < (to === undefined ? lines.length : to); i++) if (re.test(lines[i])) return i;
  return -1;
}

function lastLine(lines, re) {
  for (let i = lines.length - 1; i >= 0; i--) if (re.test(lines[i])) return i;
  return -1;
}

// The page's script, read back from just above the script region, with only
// whitespace and HTML comments allowed between the two.
function pageScript(lines, region, file) {
  let before = lines.slice(0, region.open).join('\n');
  for (;;) {
    before = before.replace(/\s+$/, '');
    if (!/-->$/.test(before)) break;
    before = before.slice(0, before.lastIndexOf('<!--'));
  }
  if (!/<\/script>$/.test(before)) {
    fail(file, region.open + 1, 'the script region is not preceded by <script data-demo-page>');
  }
  const start = before.lastIndexOf('<script');
  const tag = before.slice(start, before.indexOf('>', start) + 1);
  const line = before.slice(0, start).split('\n').length;
  if (tag !== '<script data-demo-page>') {
    fail(file, line, 'the script just above the script region is ' + tag + ', not <script data-demo-page>');
  }
  return { body: before.slice(start + tag.length, before.length - '</script>'.length), line: line };
}

function assertPage(file, text, parsed) {
  const lines = parsed.lines;
  const regions = parsed.regions;
  if (!regions.length) fail(file, 0, 'not migrated: no demo-chrome markers');
  if (text.indexOf('\r') >= 0) fail(file, text.slice(0, text.indexOf('\r')).split('\n').length, 'carries a carriage return; pages are LF-only');

  // 1. Structure: the counts.
  const by = {};
  REGIONS.forEach(function (name) { by[name] = regions.filter(function (r) { return r.name === name; }); });
  ['head', 'css', 'crossfade', 'controls', 'script'].forEach(function (name) {
    if (by[name].length !== 1) {
      fail(file, by[name].length ? by[name][1].open + 1 : 0, 'expected one ' + name + ' region, found ' + by[name].length);
    }
  });
  const head = by.head[0];
  const css = by.css[0];
  const crossfade = by.crossfade[0];
  const controls = by.controls[0];
  const script = by.script[0];
  const sound = controls.flags.indexOf('sound') >= 0;
  if (by['sound-mirror'].length && !sound) {
    fail(file, by['sound-mirror'][0].open + 1, 'a sound-mirror on a page whose controls are not +sound');
  }

  // 2. Placement.
  const headOpen = firstLine(lines, /<head[\s>]/);
  const headClose = firstLine(lines, /<\/head>/);
  const bodyOpen = firstLine(lines, /<body[\s>]/);
  const bodyClose = lastLine(lines, /<\/body>/);
  if (headOpen < 0 || headClose < 0 || bodyOpen < 0 || bodyClose < 0) fail(file, 0, 'no <head> and <body> to place regions in');
  if (!(head.open > headOpen && head.close < headClose)) fail(file, head.open + 1, 'head lies outside <head>');

  const styles = lines.reduce(function (n, l) { return n + (/<style[\s>]/.test(l) ? 1 : 0); }, 0);
  if (styles !== 1) fail(file, 0, 'expected the page\'s single <style>, found ' + styles);
  const styleOpen = firstLine(lines, /<style[\s>]/);
  const styleClose = firstLine(lines, /<\/style>/, styleOpen);
  [css, crossfade].forEach(function (r) {
    if (!(r.open > styleOpen && r.close < styleClose)) fail(file, r.open + 1, r.name + ' lies outside the page\'s <style>');
  });
  if (css.close > crossfade.open) fail(file, crossfade.open + 1, 'crossfade comes before css');
  for (let i = crossfade.close + 1; i < styleClose; i++) {
    if (lines[i].trim()) fail(file, i + 1, 'only whitespace may follow the crossfade before </style>, so it stays the last rule');
  }
  if (!/^\s*<\/style>/.test(lines[styleClose])) fail(file, styleClose + 1, 'only whitespace may come before </style>');

  const firstReveal = firstLine(lines, /\sdata-reveal(?=[\s>=])/, bodyOpen);
  if (!(controls.open > bodyOpen)) fail(file, controls.open + 1, 'controls lies outside <body>');
  if (firstReveal >= 0 && controls.close > firstReveal) fail(file, controls.open + 1, 'controls comes after the first data-reveal, line ' + (firstReveal + 1));
  by['sound-mirror'].forEach(function (r) {
    if (!(r.open > controls.close && r.close < bodyClose)) fail(file, r.open + 1, 'a sound-mirror lies before controls or outside <body>');
  });
  const last = by['sound-mirror'].concat([controls]).reduce(function (m, r) { return Math.max(m, r.close); }, 0);
  if (!(script.open > last && script.close < bodyClose)) fail(file, script.open + 1, 'script lies before controls or a mirror, or outside <body>');

  const own = pageScript(lines, script, file);
  if (own.body.indexOf('window.demoPage =') < 0) fail(file, own.line, '<script data-demo-page> does not set window.demoPage =');

  // 3. No chrome outside the regions, and no chrome selector but the
  // cluster's placement, after the chrome's own rules.
  const inside = new Array(lines.length).fill(false);
  regions.forEach(function (r) { for (let i = r.open; i <= r.close; i++) inside[i] = true; });
  lines.forEach(function (line, i) {
    if (inside[i]) return;
    OUTSIDE.forEach(function (needle) {
      if (line.indexOf(needle) >= 0) fail(file, i + 1, needle + ' outside a region; that is the chrome\'s');
    });
    if (CHROME_SELECTOR.test(line)) fail(file, i + 1, 'a chrome selector outside the css region: ' + line.trim());
    if (CONTROLS_SELECTOR.test(line) && i < css.close) fail(file, i + 1, '.demo__controls may only be placed after the css region closes');
  });

  // 4. The tokens the chrome reads.
  const outside = lines.filter(function (l, i) { return !inside[i]; }).join('\n');
  TOKENS.forEach(function (t) {
    if (!new RegExp('--demo-' + t + '\\s*:').test(outside)) fail(file, 0, '--demo-' + t + ' is not declared; the chrome reads it');
  });

  // 5. The face the chrome names.
  const headText = lines.slice(headOpen, headClose).filter(function (l, i) { return !inside[headOpen + i]; }).join('\n');
  if (!/<link\b[^>]*\bhref="[^"]*family=Fragment\+Mono[^"]*"[^>]*>/.test(headText)) {
    fail(file, headOpen + 1, 'the head does not load Fragment Mono, the face the switches are set in');
  }

  // 6. The page's script: it parses, it leaves the chrome's strings to the
  // chrome, and it says what the sound does exactly when there is one.
  try {
    new vm.Script(own.body, { filename: file + ' <script data-demo-page>' });
  } catch (err) {
    fail(file, own.line, '<script data-demo-page> does not parse: ' + err.message);
  }
  const key = own.body.match(/(['"])(a11y\.lang|a11y\.theme|sound)\1\s*:/);
  if (key) fail(file, own.line, 'the page table defines \'' + key[2] + '\', which is the chrome\'s own string');
  const declares = /^\s*sound\s*:/m.test(own.body);
  if (sound && !declares) fail(file, own.line, 'controls is +sound but window.demoPage has no sound:');
  if (!sound && declares) fail(file, own.line, 'window.demoPage has sound: but controls is not +sound');
  let demo;
  try {
    const sandbox = { window: {} };
    vm.runInNewContext(own.body, sandbox, { timeout: 1000 });
    demo = sandbox.window.demoPage;
  } catch (err) {
    fail(file, own.line, '<script data-demo-page> throws when run: ' + err.message);
  }
  if (!demo || typeof demo !== 'object' || !demo.da || typeof demo.da !== 'object') {
    fail(file, own.line, 'window.demoPage.da is not a table');
  }
  if (demo.applied !== undefined && typeof demo.applied !== 'function') fail(file, own.line, 'window.demoPage.applied is not a function');
  if (sound) {
    const s = demo.sound || {};
    const token = typeof s.roots === 'string' && typeof s.token === 'string' && /^--/.test(s.token) && typeof s.value === 'string';
    const arms = typeof s.arms === 'string';
    if (token === arms) fail(file, own.line, 'window.demoPage.sound is neither { roots, token, value } nor { arms }');
  }

  return { sound: sound };
}

/* ---- building ----------------------------------------------------------- */

function generate(src, text, file) {
  const parsed = parse(text, file);
  const info = assertPage(file, text, parsed);
  const lines = parsed.lines;
  const out = [];
  const generated = [];
  let at = 0;
  parsed.regions.forEach(function (r) {
    for (; at < r.open; at++) out.push(lines[at]);
    const body = indent(render(src, r.name, info.sound), r.pad);
    out.push(opening(r));
    out.push(body);
    out.push(lines[r.close]);
    generated.push({ region: r, body: body });
    at = r.close + 1;
  });
  for (; at < lines.length; at++) out.push(lines[at]);
  return { text: out.join('\n'), generated: generated };
}

// The page with every region emptied and every marker in its canonical
// form: what nobody but a person writes. Equal before and after a build is
// the proof that nothing outside the markers moved.
function strip(text, file) {
  const parsed = parse(text, file);
  const out = [];
  let at = 0;
  parsed.regions.forEach(function (r) {
    for (; at < r.open; at++) out.push(parsed.lines[at]);
    out.push(opening(r));
    out.push(parsed.lines[r.close].replace(/^[ \t]*/, r.pad));
    at = r.close + 1;
  });
  for (; at < parsed.lines.length; at++) out.push(parsed.lines[at]);
  return out.join('\n');
}

function build(src, text, file) {
  const first = generate(src, text, file);
  const out = first.text;

  // 7. Output.
  first.generated.forEach(function (g) {
    const line = g.region.open + 1;
    if (g.body.indexOf('{{') >= 0) fail(file, line, g.region.name + ': a placeholder was left unfilled');
    if (g.region.name === 'head' || g.region.name === 'script') {
      const m = g.body.match(/<script>([\s\S]*?)<\/script>/);
      if (!m) fail(file, line, g.region.name + ': no <script> in the generated region');
      try {
        new vm.Script(m[1], { filename: file + ' ' + g.region.name });
      } catch (err) {
        fail(file, line, g.region.name + ': the generated script does not parse: ' + err.message);
      }
    }
  });
  if (out.indexOf('\r') >= 0) fail(file, 0, 'the output carries a carriage return');
  if (/\n$/.test(out) !== /\n$/.test(text)) fail(file, 0, 'the final newline was not preserved');

  // 8. Idempotence and confinement.
  if (generate(src, out, file).text !== out) fail(file, 0, 'a second build would change the page again');
  if (strip(out, file) !== strip(text, file)) fail(file, 0, 'the build moved something outside the markers');

  return out;
}

/* ---- the command -------------------------------------------------------- */

function discover(names) {
  const all = fs.readdirSync(ROOT).filter(function (name) {
    if (!/^\d{4}-\d{2}-/.test(name) && name !== '_template') return false;
    return fs.statSync(path.join(ROOT, name)).isDirectory() && fs.existsSync(path.join(ROOT, name, 'demo.html'));
  }).sort();
  if (!names.length) return all;
  return names.map(function (name) {
    const folder = name.replace(/[\\/]+$/, '').replace(/[\\/]demo\.html$/, '');
    if (all.indexOf(folder) < 0) throw new ChromeError(name + ': not a study folder with a demo.html');
    return folder;
  });
}

function main(argv) {
  const check = argv.indexOf('--check') >= 0;
  const unknown = argv.filter(function (a) { return /^-/.test(a) && a !== '--check'; });
  if (unknown.length) {
    console.error('unknown option ' + unknown.join(' ') + '\nusage: node tools/demo-chrome/build.js [--check] [folder ...]');
    return 2;
  }
  let src;
  let folders;
  try {
    src = loadSources();
    folders = discover(argv.filter(function (a) { return !/^-/.test(a); }));
  } catch (err) {
    if (!(err instanceof ChromeError)) throw err;
    console.error(err.message);
    return 2;
  }

  const pages = [];
  const errors = [];
  folders.forEach(function (folder) {
    const file = folder + '/demo.html';
    const abs = path.join(ROOT, folder, 'demo.html');
    const text = fs.readFileSync(abs, 'utf8');
    try {
      pages.push({ file: file, abs: abs, text: text, out: build(src, text, file) });
    } catch (err) {
      if (!(err instanceof ChromeError)) throw err;
      errors.push(err.message);
    }
  });

  if (errors.length) {
    errors.forEach(function (e) { console.error(e); });
    console.error(errors.length + ' of ' + folders.length + ' pages failed; nothing was written');
    return 2;
  }

  const stale = pages.filter(function (p) { return p.out !== p.text; });
  if (check) {
    if (stale.length) {
      stale.forEach(function (p) { console.error('out of date: ' + p.file); });
      console.error('run node tools/demo-chrome/build.js');
      return 1;
    }
    console.log(pages.length + ' pages up to date');
    return 0;
  }
  stale.forEach(function (p) {
    fs.writeFileSync(p.abs, p.out);
    console.log('wrote ' + p.file);
  });
  console.log(stale.length + ' written, ' + (pages.length - stale.length) + ' already up to date');
  return 0;
}

process.exitCode = main(process.argv.slice(2));

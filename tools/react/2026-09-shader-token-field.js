  octaves:  { type: "number", label: "Octaves", control: "slider", min: 1, max: 8, step: 1, defaultValue: defaults.octaves },
  warp:     { type: "number", label: "Warp", control: "slider", min: 0, max: 1, step: 0.01, defaultValue: defaults.warp },
  relief:   { type: "number", label: "Relief", control: "slider", min: 0, max: 2, step: 0.05, defaultValue: defaults.relief },
